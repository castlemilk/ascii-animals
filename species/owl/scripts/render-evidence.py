#!/usr/bin/env python3
"""Rasterize executed glyph grids with an installed font. Not browser screenshots."""
from pathlib import Path
import json, hashlib, os
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
out = root / 'evidence'
data = json.loads((out / 'logical-frames.json').read_text())
font_path = Path(os.environ.get('OWL_FONT', '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf'))
if not font_path.is_file():
    raise SystemExit('Set OWL_FONT to an installed monospaced font; no font is downloaded or bundled.')
bg, fg, faint, accent = '#101919', '#d6dec9', '#9cac9d', '#c7d4a5'

def render(frame, font_size=12, title=None, footer=True):
    font = ImageFont.truetype(str(font_path), font_size)
    label = ImageFont.truetype(str(font_path), 11)
    cellw = font.getlength('M')
    cellh = cellw / .55
    width = round(frame['cols'] * cellw) + 40
    height = round(frame['rows'] * cellh) + 85
    im = Image.new('RGB', (width, height), bg)
    draw = ImageDraw.Draw(im)
    header = title or f"OWL / tick {frame.get('tick', 0):03d} / {frame.get('phase', 'poster')}"
    draw.text((20, 16), header, font=label, fill=accent)
    for row, line in enumerate(frame['text'].split('\n')):
        draw.text((20, 43 + row * cellh), line, font=font, fill=fg, anchor='lt')
    if footer:
        draw.text((20, height - 24), 'Executed glyph grid / Pillow / not browser pixels', font=label, fill=faint)
    return im

frames = [render(f) for f in data['animation']]
# 12Hz sampling of explicit 60Hz simulation. GIF repeats the 8-second replay;
# it is not claimed to be a period of the owl's independent idle oscillations.
durations = [80, 80, 90] * (len(frames) // 3 + 1)
frames[0].save(out / 'owl-replay.gif', save_all=True, append_images=frames[1:], duration=durations[:len(frames)], loop=0, optimize=True)

def sheet(items, filename, cols, font_size):
    panels = [render(f, font_size=font_size, title=f.get('title'), footer=False) for f in items]
    w, h = panels[0].size
    rows = (len(panels) + cols - 1) // cols
    canvas = Image.new('RGB', (w * cols, h * rows + 64), '#091011')
    draw = ImageDraw.Draw(canvas)
    font = ImageFont.truetype(str(font_path), 14)
    draw.text((20, 13), 'OWL / ORIGINAL PROCEDURAL ASCII / REVIEW EVIDENCE', font=font, fill=fg)
    draw.text((20, 36), 'Actual sampled cells, rasterized with Pillow + installed DejaVu Sans Mono; browser not launched.', font=ImageFont.truetype(str(font_path), 11), fill=faint)
    for i, panel in enumerate(panels): canvas.paste(panel, ((i % cols)*w, 64+(i//cols)*h))
    canvas.save(out / filename)

sheet(data['selected'], 'contact-sheet.png', 4, 9)
sheet(data['smallest'], 'small-grid-sheet.png', 3, 11)
render(data['selected'][0], font_size=16, title='OWL / THE NIGHT WATCH / NEUTRAL POSTER').save(out / 'owl-poster.png')
(out / 'raster-provenance.json').write_text(json.dumps({
    'evidenceKind': 'Logical text output rasterization, not browser or native Canvas',
    'fontFileUsedLocally': str(font_path), 'fontSha256': hashlib.sha256(font_path.read_bytes()).hexdigest(),
    'fontBundled': False, 'cellAspect': .55,
    'source': 'logical-frames.json generated by capture-logical.mjs',
    'gif': '12Hz frame sampling of 60Hz ticks; repeats the recorded 8-second sequence with a reset seam',
}, indent=2)+'\n')
print('Wrote contact-sheet.png, small-grid-sheet.png, owl-poster.png and owl-replay.gif')
